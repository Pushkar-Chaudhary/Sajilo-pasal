const nodemailer = require('nodemailer');

const requiredEmailConfig = ['EMAIL_USER', 'CLIENT_ID', 'CLIENT_SECRET', 'REFRESH_TOKEN'];

function getTransporter() {
    const missingConfig = requiredEmailConfig.filter((key) => !process.env[key]);
    if (missingConfig.length > 0) {
        throw new Error(`Missing email configuration: ${missingConfig.join(', ')}`);
    }

    return nodemailer.createTransport({
        service: 'gmail',
        auth: {
            type: 'OAuth2',
            user: process.env.EMAIL_USER,
            clientId: process.env.CLIENT_ID,
            clientSecret: process.env.CLIENT_SECRET,
            refreshToken: process.env.REFRESH_TOKEN,
        },
    });
}

const sendEmail = async (to, subject, text, html) => {
    const transporter = getTransporter();
    const info = await transporter.sendMail({
        from: `"Hamro Sewa" <${process.env.EMAIL_USER}>`,
        to,
        subject,
        text,
        html,
    });

    console.log('Message sent:', info.messageId);
    return info;
};

async function sendRegistrationEmail(userEmail, name) {
    const subject = 'Welcome to Backend Ledger!';
    const text = `Hello ${name},\n\nThank you for registering at Backend Ledger. We're excited to have you on board!\n\nBest regards,\nThe Backend Ledger Team`;
    const html = `<p>Hello ${name},</p><p>Thank you for registering at Backend Ledger. We're excited to have you on board!</p><p>Best regards,<br>The Backend Ledger Team</p>`;

    await sendEmail(userEmail, subject, text, html);
}

